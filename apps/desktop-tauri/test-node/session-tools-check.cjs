'use strict';
const assert = require('node:assert/strict');
const S = require('../../desktop-daemon/src/sessions.cjs');
const h = new S.ToolHistory();
const event = (type, id, toolName = 'read') => ({ type, toolCallId: id, toolName, args: { secret: 'never-project' } });
h.accept(event('tool_execution_end', 'unknown'));
assert.deepEqual(h.view(), { total: 0, steps: [] });
h.accept(event('tool_execution_start', 'a'));
h.accept(event('tool_execution_start', 'a'));
h.accept(event('tool_execution_end', 'a'));
h.accept(event('tool_execution_start', 'b', 'bash'));
h.accept({ ...event('tool_execution_end', 'b', 'bash'), isError: true });
assert.deepEqual(h.view(), { total: 2, steps: [{ index: 1, name: 'read', state: 'done' }, { index: 2, name: 'bash', state: 'error' }] });
assert.throws(() => S.buildTools({ total: 1, steps: [{ index: 1, state: 'done' }] }));
const row = { id: 's-0123abcd', kind: 'pi', cwd: 'project', state: 'running', origin: null, tools: h.view() };
assert.deepEqual(S.buildSessions([row])[0].tools, h.view());
assert.ok(!JSON.stringify(h.view()).includes('never-project'));
for (let i = 0; i < 25; i++) h.accept(event('tool_execution_start', `next-${i}`));
assert.equal(h.view().total, 27);
assert.equal(h.view().steps.length, 20);
assert.equal(h.view().steps.at(-1).index, 27);
h.accept(event('tool_execution_start', 'bad', '/private/path'));
assert.equal(h.view().total, 27);
const capped = new S.ToolHistory();
for (let i = 0; i < 4097; i++) capped.accept(event('tool_execution_start', `cap-${i}`));
assert.equal(capped.view(), null, 'an exhausted dedupe budget reports unavailable rather than a false total');
const { IslandServer } = require('../../desktop-daemon/src/server.cjs');
(async () => {
  const engine = { pid: process.pid, sessionFile: 'fixture-session', sessionEpoch: 0, status: 'ready' };
  const own = { ...row, id: S.sessionIdForPid(process.pid) }; delete own.tools;
  const foreign = { ...row, id: 's-ffffffff', kind: 'codex' }; delete foreign.tools;
  const server = new IslandServer({ token: 'fixture-token-not-a-secret', runtimeDir: '/tmp/unused-session-tools', engine, sessions: { snapshot: async () => ({ sessions: [own, foreign], truncated: false }) } });
  await server.sessionsOutcome(); // prime the discovery cache before tools arrive
  server.onEngineEvent(event('tool_execution_start', 'a'));
  server.onEngineEvent(event('tool_execution_end', 'a'));
  server.onEngineEvent(event('tool_execution_start', 'b', 'bash'));
  server.onEngineEvent(event('tool_execution_end', 'b', 'bash'));
  let result = await server.sessionsOutcome();
  assert.equal(result.sessions[0].tools.total, 2);
  assert.equal(result.sessions[0].tools.steps[1].state, 'done');
  assert.equal(result.sessions[1].tools, undefined);
  engine.sessionEpoch++;
  result = await server.sessionsOutcome();
  assert.equal(result.sessions[0].tools, undefined, 'switching conversations clears the old stream');
  server.onEngineEvent(event('tool_execution_start', 'fresh'));
  result = await server.sessionsOutcome();
  assert.equal(result.sessions[0].tools.epoch, 1, 'a new conversation is distinguishable even with the same process and tool count');
  console.log('session-tools-check: ingestion, cache overlay, isolation, lifecycle and bounds pass');
})().catch(error => { console.error(error); process.exitCode = 1; });
