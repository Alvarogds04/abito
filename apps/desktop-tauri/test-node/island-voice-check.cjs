'use strict';
const assert = require('node:assert/strict');
const V = require('../frontend/island-voice.js');
assert.deepEqual(V.OUTCOMES, ['success', 'failure', 'question']);
assert.equal(V.RESULT_MS, 2000);
assert.equal(V.FADE_MS, 200);
const css = require('node:fs').readFileSync(require('node:path').resolve(__dirname, '../frontend/island-voice.css'), 'utf8');
assert(/transition: opacity 0\.2s/.test(css) && !/style=/.test(css));
assert.equal(V.heardOf({ text: 'pon música' }), 'pon música');
assert.equal(V.heardOf({ text: 'a\u0000b' }), 'a b');
assert.equal(V.heardOf({ text: 'x'.repeat(1000) }).length, V.MAX_TEXT);
for (const bad of [null, [], 'x', {}, { text: 5 }]) assert.equal(V.heardOf(bad), null);
assert.deepEqual(V.resultOf({ outcome: 'success', message: 'Hecho' }), { outcome: 'success', message: 'Hecho' });
assert.deepEqual(V.resultOf({ outcome: 'question', message: 7 }), { outcome: 'question', message: '' });
for (const bad of [null, {}, { outcome: 'weird' }, [], 'x']) assert.equal(V.resultOf(bad), null);
assert.equal(V.askOf({ text: '  hola ' }), 'hola');
assert.equal(V.askOf({ text: '   ' }), null);
assert.equal(V.revealPlan({ state: 'hidden', phase: 'compact' }), 'expand');
assert.equal(V.revealPlan({ state: 'visible', phase: 'compact' }), 'expand');
assert.equal(V.revealPlan({ state: 'visible', phase: 'expanded' }), 'none');
assert.equal(V.revealPlan(null), 'none');
const src = require('node:fs').readFileSync(require('node:path').resolve(__dirname, '../frontend/island-voice.js'), 'utf8');
assert(!/innerHTML|eval\(|invoke\(/.test(src.replace(/\/\*[\s\S]*?\*\//g, '')), 'no innerHTML, eval or invoke: only window.desktop verbs');
console.log('island-voice-check ok');
