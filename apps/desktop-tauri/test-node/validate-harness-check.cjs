'use strict';
const assert = require('node:assert/strict');
const { buildReport, exitCode, spanishSummary } = require('../packaging/validate/report.cjs');
const pass = { name: 'isla-compacta', verdict: 'pass', png: '/tmp/compacta.png' };
const unknown = { name: 'microfono', verdict: 'unverifiable', reason: 'sin dispositivo' };
const fail = { name: 'isla-atajo', verdict: 'fail', reason: 'debajo de rival' };
const report = buildReport([pass, unknown, fail], { head: 'abc', durationMs: 12 });
assert.deepEqual(report.counts, { pass: 1, fail: 1, unverifiable: 1 });
assert.deepEqual(report.scenes, [pass, unknown, fail], 'retain each scene and its screenshot/reason');
assert.equal(report.head, 'abc');
assert.equal(report.durationMs, 12);
assert.equal(exitCode(report), 1);
assert.equal(exitCode(buildReport([pass, unknown])), 0);
assert.equal(exitCode(buildReport([])), 1, 'empty run must not approve a preview');
assert.match(spanishSummary(report), /isla-compacta: anda/);
assert.match(spanishSummary(report), /isla-atajo: falla \(debajo de rival\)/);
assert.match(spanishSummary(report), /microfono: no verificable aquí \(sin dispositivo\)/);
assert.match(spanishSummary(report), /1 anda.*1 falla.*1 no verificable/);
assert.throws(() => buildReport([{ name: 'bad', verdict: 'maybe' }]), /verdict/);
assert.throws(() => buildReport([{ name: 'bad', verdict: 'fail' }]), /reason/);
assert.throws(() => buildReport([pass, pass]), /duplicate/);
console.log('validate-harness: 14 checks passed');
